import { promises as fs } from "node:fs";
import path from "node:path";

import yaml from "js-yaml";
import { format, resolveConfig } from "prettier";

const root = path.resolve(import.meta.dirname, "../..");
const contentRoot = path.join(root, "docs");
const outputPath = path.join(root, "scripts/blume/route-manifest.json");
const redirectsPath = path.join(root, "scripts/blume/openapi-redirects.mjs");

const assertUnique = (values, label) => {
  const seen = new Set();
  const duplicates = new Set();
  for (const value of values) {
    if (seen.has(value)) duplicates.add(value);
    seen.add(value);
  }
  if (duplicates.size) throw new Error(`Duplicate ${label}: ${[...duplicates].join(", ")}`);
};

const slugify = (value) =>
  value
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const routeFromFile = (file, id) => {
  const parsed = path.parse(path.relative(contentRoot, file));
  const segments = parsed.dir ? parsed.dir.split(path.sep) : [];
  const finalSegment = id || parsed.name;

  if (finalSegment !== "index") {
    segments.push(finalSegment);
  }

  return `/${segments.join("/")}`.replace(/\/$/, "") || "/";
};

const readFrontmatter = (source) => {
  if (!source.startsWith("---\n")) {
    return {};
  }

  const end = source.indexOf("\n---", 4);
  if (end === -1) {
    return {};
  }

  return yaml.load(source.slice(4, end)) || {};
};

const walk = async (directory) => {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.name.startsWith("_")) {
      continue;
    }

    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(entryPath)));
    } else if (/\.mdx?$/.test(entry.name)) {
      files.push(entryPath);
    }
  }

  return files;
};

const buildOpenApiRedirects = async (apiName) => {
  const spec = yaml.load(await fs.readFile(path.join(root, `openapi/${apiName}.yml`), "utf8"));
  const mapping = JSON.parse(await fs.readFile(path.join(root, `public/${apiName}-mapping.json`), "utf8"));
  const operations = [];

  for (const pathItem of Object.values(spec.paths || {})) {
    for (const operation of Object.values(pathItem || {})) {
      if (!(operation && typeof operation === "object" && operation.operationId)) {
        continue;
      }

      const legacy = mapping[operation.operationId];
      if (!legacy?.filePath) {
        throw new Error(`Missing ${apiName.toUpperCase()} file mapping for ${operation.operationId}`);
      }

      const tag = operation.tags?.[0] || "default";
      operations.push({
        operationId: operation.operationId,
        from: `/references/${legacy.filePath.replace(/^\/+/, "").replace(/\.mdx?$/, "")}`,
        to: `/references/${apiName}/${slugify(tag)}/${slugify(operation.operationId)}`,
      });
    }
  }

  return operations.sort((a, b) => a.from.localeCompare(b.from));
};

const files = await walk(contentRoot);
const pages = [];

for (const file of files) {
  const source = await fs.readFile(file, "utf8");
  const frontmatter = readFrontmatter(source);
  const route = routeFromFile(file, frontmatter.id);

  pages.push({
    file: path.relative(root, file),
    route,
    publicRoute: route === "/" ? "/docs" : `/docs${route}`,
  });
}

const openapi = [...(await buildOpenApiRedirects("cdi")), ...(await buildOpenApiRedirects("fdi"))];
assertUnique(
  openapi.map(({ from }) => from),
  "OpenAPI redirect sources",
);
assertUnique(
  openapi.map(({ to }) => to),
  "OpenAPI operation routes",
);

for (const operation of openapi) {
  if (!pages.some((page) => page.route === operation.to)) {
    pages.push({
      file: `openapi/${operation.to.split("/")[2]}/${operation.operationId}`,
      route: operation.to,
      publicRoute: `/docs${operation.to}`,
    });
  }
}

assertUnique(
  pages.map(({ file }) => file),
  "manifest file identities",
);
assertUnique(
  pages.map(({ route }) => route),
  "manifest routes",
);

pages.sort((a, b) => a.route.localeCompare(b.route));

const manifest = {
  counts: {
    pages: pages.length,
    openapiOperations: openapi.length,
  },
  pages,
  openapi,
};

await fs.writeFile(outputPath, `${JSON.stringify(manifest, null, 2)}\n`);
const prettierConfig = (await resolveConfig(redirectsPath)) ?? {};
await fs.writeFile(
  redirectsPath,
  await format(
    `// Generated by scripts/blume/create-route-manifest.mjs.\nexport const openApiRedirects = ${JSON.stringify(
      openapi.map(({ from, to }) => ({ from, to })),
      null,
      2,
    )};\n`,
    { ...prettierConfig, parser: "babel" },
  ),
);
console.log(
  `Wrote ${pages.length} pages and ${openapi.length} OpenAPI operations to ${path.relative(root, outputPath)}`,
);
